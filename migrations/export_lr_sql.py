#!/usr/bin/env python3
"""Export migration 005 for SQL Editor without changing its recorded checksum."""
import argparse
import hashlib
import importlib
from pathlib import Path
import sys
from uuid import NAMESPACE_URL, uuid5

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
migration = importlib.import_module('migrations.005_centralized_lr')


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def render_sql(schema='public'):
    if not schema or '\x00' in schema:
        raise ValueError('Specify a PostgreSQL schema name.')
    quoted = '"' + schema.replace('"', '""') + '"'
    template = migration.SQL_FILE.read_text()
    checksum = hashlib.sha256(template.encode()).hexdigest()
    ddl = template.replace('__SCHEMA__', quoted)
    if '$lr_ddl$' in ddl:
        raise ValueError('DDL delimiter collision; update the exporter.')
    version = literal(migration.VERSION)
    return f'''-- Generated by migrations/export_lr_sql.py. Run the ENTIRE file in SQL Editor.
-- Preserves the original migration 005 checksum; never deletes partial state.
BEGIN;
SET LOCAL search_path = {quoted};
SET LOCAL lock_timeout = '15s';
SET LOCAL statement_timeout = '120s';
SELECT pg_advisory_xact_lock(723910042005);
DO $lr_migration$
DECLARE previous text; historical_count bigint; original_acl text; item text;
BEGIN
 IF to_regclass('admin_migration_runs') IS NULL OR to_regclass('consignments') IS NULL THEN
   RAISE EXCEPTION 'Existing shipment schema and migration ledger required in schema %', {literal(schema)};
 END IF;
 SELECT target_digest INTO previous FROM admin_migration_runs WHERE version = {version};
 IF FOUND THEN
   IF previous <> '{checksum}' THEN
     RAISE EXCEPTION 'Migration 005 checksum differs; do not overwrite recorded history';
   END IF;
   FOREACH item IN ARRAY ARRAY['issuing_locations','lr_sequences','lr_requests','lr_imports','lr_audit_log'] LOOP
     IF to_regclass(item) IS NULL THEN RAISE EXCEPTION 'Migration 005 recorded but table % is missing', item; END IF;
   END LOOP;
   RAISE NOTICE 'Migration 005 is already recorded; no changes made';
   RETURN;
 END IF;
 FOREACH item IN ARRAY ARRAY['issuing_locations','lr_sequences','lr_requests','lr_imports','lr_audit_log'] LOOP
   IF to_regclass(item) IS NOT NULL THEN
     RAISE EXCEPTION 'Unrecorded LR table % already exists. Stop and inspect the partial migration; do not drop tables or counters', item;
   END IF;
 END LOOP;
 SELECT count(*) INTO historical_count FROM consignments;
 SELECT relacl::text INTO original_acl FROM pg_class WHERE oid='consignments'::regclass;
 EXECUTE $lr_ddl$
{ddl}
$lr_ddl$;
 IF (SELECT count(*) FROM consignments) <> historical_count THEN
   RAISE EXCEPTION 'Historical shipment preservation check failed';
 END IF;
 INSERT INTO admin_migration_runs(version, namespace, source_digest, target_digest,
   source_schema, counts, warnings, completed_at)
 VALUES ({version}, '{uuid5(NAMESPACE_URL, migration.VERSION)}'::uuid,
   '{checksum}', '{checksum}',
   jsonb_build_object('upgrade','centralized_lr','original_consignments_acl',original_acl),
   jsonb_build_object('consignments',jsonb_build_object('preserved_rows',historical_count)),
   '[]'::jsonb, clock_timestamp());
END
$lr_migration$;
COMMIT;
-- Read-only verification. Issuance still requires reviewed opening counters.
SELECT version, completed_at FROM {quoted}.admin_migration_runs WHERE version={version};
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--schema', default='public')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(render_sql(args.schema))
    print('SQL Editor migration exported. No database connection or migration was performed.')


if __name__ == '__main__':
    main()
